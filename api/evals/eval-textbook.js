#!/usr/bin/env -S deno run --allow-net --allow-read --allow-write

/**
 * Subjective-review sample generator for /textbook. Same human-in-the-loop
 * loop as the /lookup sample tooling this pattern derives from: "look at real
 * output, decide what a better output would be, mine the differences for
 * prompt edits."
 *
 * It drives the REAL, already-running dev server (no prompt fork, no mocked
 * LLM) through /textbook's full TWO-CALL flow and writes one file per case to
 * api/evals/samples/<slug>.yaml:
 *
 *   1. POST /textbook { topic, language, ability, llm }        → { questions, checklist }
 *   2. Auto-answer: each question → its own `default`; checklist → the checked
 *      items (or ALL items with --checklist=all, or all items when nothing is
 *      checked). This makes the sample reproducible without a TTY, while still
 *      exercising the same generate call a real client would issue.
 *   3. POST /textbook { ..., context }                         → { title, groups }
 *
 * File shape:
 *   - Above the divider: `ideal` — hand-editable YAML, English-only fields
 *     (phrasebook `title`, group `title`, each card's English gloss). Seeded
 *     once from the first real response, then NEVER touched again by this
 *     script. Add a free-form `note:`/`notes:` anywhere to explain a gap
 *     between ideal and actual.
 *   - Below the divider: `actual` — the verbatim request inputs + the raw
 *     questions response + the raw generate response + a timestamp, byte-for-
 *     byte what the API returned. Fully replaced on every run; never hand-edit.
 *
 * This file is for a human/LLM to read side by side, not for a script to parse
 * back — it is intentionally not one valid YAML or JSON document.
 *
 * USAGE
 *   deno run --allow-net --allow-read --allow-write evals/eval-textbook.js \
 *     [--topic="salsa dancing"] [--language=es] [--ability=beginner] \
 *     [--llm=google] [--checklist=default|all] [--url=http://localhost:8080] [--force]
 *
 * Any of topic/language/ability/llm omitted as a flag is prompted for
 * interactively (requires a real TTY on stdin — pass every flag for
 * non-interactive/scripted use).
 *
 * Requires the dev server already running (`cd src && npm run dev`).
 */

const ENUMS = {
  language: ['zh', 'ja', 'es', 'cs'],
  ability: ['none', 'beginner', 'intermediate', 'advanced', 'neutral'],
  llm: ['google', 'claude', 'chatgpt'],
  checklist: ['default', 'all'],
};
const DEFAULTS = { ability: 'beginner', llm: 'google', checklist: 'default' };

const SAMPLES_DIR = new URL('./samples/', import.meta.url);
const DIVIDER = [
  '# ============================================================',
  '# ACTUAL — regenerated by eval-textbook.js on every run.',
  '# Everything below this line is discarded and replaced on rerun.',
  '# ============================================================',
].join('\n');

// ---------------------------------------------------------------------------
// CLI args + interactive prompting
// ---------------------------------------------------------------------------

function parseFlags(argv) {
  const flags = { url: 'http://localhost:8080', force: false };
  for (const arg of argv) {
    if (arg === '--force') flags.force = true;
    else if (arg.startsWith('--')) {
      const eq = arg.indexOf('=');
      if (eq === -1) throw new Error(`Malformed flag (expected --key=value): ${arg}`);
      flags[arg.slice(2, eq)] = arg.slice(eq + 1);
    }
  }
  return flags;
}

function promptTopic(flags) {
  if (flags.topic) return flags.topic;
  const answer = prompt('Topic (the situation, e.g. "salsa dancing" or "dinner with my in-laws"): ');
  if (answer === null) {
    throw new Error(
      'No value for "topic" and stdin is not an interactive terminal. ' +
      'Pass every param as a --flag for non-interactive use.',
    );
  }
  const trimmed = answer.trim();
  if (!trimmed) throw new Error('Topic is required.');
  return trimmed;
}

function promptEnum(flags, key, { required }) {
  if (flags[key]) {
    if (!ENUMS[key].includes(flags[key])) {
      throw new Error(`--${key}=${flags[key]} invalid; must be one of ${ENUMS[key].join(', ')}`);
    }
    return flags[key];
  }
  const def = DEFAULTS[key];
  const suffix = required ? '' : ` (default: ${def})`;
  const label = `${key[0].toUpperCase()}${key.slice(1)} [${ENUMS[key].join('|')}]${suffix}: `;
  for (;;) {
    const raw = prompt(label);
    if (raw === null) {
      // stdin is not an interactive terminal.
      if (!required) return def;
      throw new Error(
        `No value for "${label}" and stdin is not an interactive terminal. ` +
        'Pass every param as a --flag for non-interactive use.',
      );
    }
    const answer = raw.trim();
    if (!answer && !required) return def;
    if (ENUMS[key].includes(answer)) return answer;
    console.log(`  invalid — must be one of ${ENUMS[key].join(', ')}`);
  }
}

function collectInput(flags) {
  return {
    topic: promptTopic(flags),
    language: promptEnum(flags, 'language', { required: true }),
    ability: promptEnum(flags, 'ability', { required: false }),
    llm: promptEnum(flags, 'llm', { required: false }),
    checklist: promptEnum(flags, 'checklist', { required: false }),
  };
}

// Sample filenames encode the served model by nickname, matching the existing
// hand-named samples (gpt-5.6-luna → "luna"). Falls back to the raw served
// model string, then the llm enum, when a nickname isn't mapped.
const MODEL_NICKNAMES = {
  'gemini-3.5-flash-lite': 'gemini',
  'gpt-5.6-luna': 'luna',
  'claude-haiku-4-5-20251001': 'haiku',
};

function slugify({ topic, language, ability }, model) {
  const raw = `${language}-${topic}-${ability}-${model}`;
  return raw
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

// ---------------------------------------------------------------------------
// minimal YAML emitter — just enough for the `ideal` shape (nested
// lists/dicts of strings). Not a general-purpose serializer.
// ---------------------------------------------------------------------------

function yamlScalar(value) {
  if (value === null || value === undefined) return 'null';
  const s = String(value);
  return `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

function emitIdealYaml(ideal, context) {
  const lines = [];
  lines.push('# ideal — hand-edit this section; preserved across reruns.');
  lines.push('# English-only. Edit gloss/title text, add or remove cards, reorder groups.');
  lines.push('# Add a `note:` field to any group (or a top-level `notes:`) to explain a');
  lines.push('# gap between ideal and actual (e.g. "too few standalone vocab words here").');
  lines.push(`title: ${yamlScalar(ideal.title)}`);

  // context — the call-1 answers + section checklist that drove generation.
  // Seeded from the actual run so the questions themselves can be reviewed:
  // fix a wrong answer, drop an irrelevant section, or add an inline `#`
  // comment beside any line to critique a question or section choice.
  const answerKeys = Object.keys(context.answers);
  if (answerKeys.length === 0) {
    lines.push('answers: {}');
  } else {
    lines.push('answers:');
    for (const key of answerKeys) {
      lines.push(`  ${yamlScalar(key)}: ${yamlScalar(context.answers[key])}`);
    }
  }
  if (context.checklist.length === 0) {
    lines.push('checklist: []');
  } else {
    lines.push('checklist:');
    for (const item of context.checklist) lines.push(`  - ${yamlScalar(item)}`);
  }

  if (ideal.groups.length === 0) {
    lines.push('groups: []');
  } else {
    lines.push('groups:');
    for (const group of ideal.groups) {
      lines.push(`  - title: ${yamlScalar(group.title)}`);
      if (group.cards.length === 0) {
        lines.push('    cards: []');
      } else {
        lines.push('    cards:');
        for (const card of group.cards) lines.push(`      - ${yamlScalar(card)}`);
      }
    }
  }
  lines.push('notes: ""');
  return lines.join('\n');
}

// ---------------------------------------------------------------------------
// strip a raw /textbook generate response to English-only fields for the seed
// ---------------------------------------------------------------------------

function stripToEnglish(response) {
  return {
    title: response.title || null,
    groups: (response.groups || []).map((group) => ({
      title: group.title,
      cards: (group.cards || []).map((c) => c.translation),
    })),
  };
}

// ---------------------------------------------------------------------------
// build the generate-call `context` from the questions response
// ---------------------------------------------------------------------------

function buildContext(questionsResponse, mode) {
  const answers = {};
  for (const q of questionsResponse.questions || []) {
    answers[q.label] = q.default;
  }
  const all = (questionsResponse.checklist || []).map((c) => c.label);
  const checked = (questionsResponse.checklist || [])
    .filter((c) => c.checked)
    .map((c) => c.label);
  // 'all' takes every item; 'default' takes the checked ones, but falls back
  // to all when the model checked nothing (so a sample is never empty).
  const checklist = mode === 'all' || checked.length === 0 ? all : checked;
  return { answers, checklist };
}

// ---------------------------------------------------------------------------
// runner
// ---------------------------------------------------------------------------

async function postTextbook(url, body) {
  const res = await fetch(`${url}/textbook`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(body),
  });
  const payload = await res.json();
  if (!res.ok) {
    throw new Error(`/textbook returned ${res.status}: ${payload.error || JSON.stringify(payload)}`);
  }
  return payload;
}

async function main() {
  const flags = parseFlags(Deno.args);
  const input = collectInput(flags);
  const base = { topic: input.topic, language: input.language, ability: input.ability, llm: input.llm };

  console.log(`Call 1 — ${flags.url}/textbook (questions) for "${input.topic}" (${input.language}, ${input.ability}, ${input.llm})...`);
  const questionsResponse = await postTextbook(flags.url, base);
  console.log(`  ${questionsResponse.questions.length} questions, ${questionsResponse.checklist.length} checklist items`);

  const context = buildContext(questionsResponse, input.checklist);
  console.log(`Call 2 — generate for ${context.checklist.length} section(s): ${context.checklist.join(', ')}`);
  const generateResponse = await postTextbook(flags.url, { ...base, context });
  const cardCount = (generateResponse.groups || []).reduce((n, g) => n + g.cards.length, 0);
  console.log(`  ${generateResponse.groups.length} groups, ${cardCount} cards`);

  await Deno.mkdir(SAMPLES_DIR, { recursive: true });
  const servedModel = generateResponse && generateResponse.usage && generateResponse.usage.model;
  const model = MODEL_NICKNAMES[servedModel] || servedModel || input.llm;
  const fileUrl = new URL(`./${slugify(input, model)}.yaml`, SAMPLES_DIR);

  const questionsAndAnswers = (questionsResponse.questions || []).map((q) => ({
    question: q.label,
    options: q.options,
    answer: context.answers[q.label],
  }));

  const actualBlock = JSON.stringify(
    {
      input,
      context,
      generatedAt: new Date().toISOString(),
      questionsAndAnswers,
      questionsResponse,
      generateResponse,
    },
    null,
    2,
  );

  let idealSection;
  let exists = true;
  let priorContent = null;
  try {
    priorContent = await Deno.readTextFile(fileUrl);
  } catch (err) {
    if (err instanceof Deno.errors.NotFound) exists = false;
    else throw err;
  }

  if (exists && !flags.force) {
    const dividerIdx = priorContent.indexOf(DIVIDER);
    idealSection = dividerIdx === -1 ? priorContent.trimEnd() : priorContent.slice(0, dividerIdx).trimEnd();
    console.log(`Preserving existing ideal section in ${fileUrl.pathname}`);
  } else {
    idealSection = emitIdealYaml(stripToEnglish(generateResponse), context);
    console.log(exists ? 'Force-regenerating ideal + actual.' : 'Seeding new ideal section from this response.');
  }

  const content = `${idealSection}\n\n${DIVIDER}\n${actualBlock}\n`;
  await Deno.writeTextFile(fileUrl, content);
  console.log(`Wrote ${fileUrl.pathname}`);
}

if (import.meta.main) {
  main().catch((err) => {
    console.error('eval-textbook failed:', err.message);
    Deno.exit(1);
  });
}

export { slugify, stripToEnglish, emitIdealYaml, buildContext, DIVIDER };
