#!/usr/bin/env -S deno run --allow-net --allow-read --allow-write --allow-env

/**
 * Subjective-review sample generator for /textbook. Same human-in-the-loop
 * loop as the /lookup sample tooling this pattern derives from: "look at real
 * output, decide what a better output would be, mine the differences for
 * prompt edits."
 *
 * It drives the REAL, already-running dev server (no prompt fork, no mocked
 * LLM) through /textbook's full TWO-CALL flow and writes one YAML file per
 * model into a per-prompt directory:
 *
 *   api/evals/<prompt-slug>/
 *   ├── context.json           # the pinned prompt + call-1 output (shared)
 *   ├── es-gemini.yaml         # <language>-<model>.yaml, one per model
 *   ├── es-haiku.yaml
 *   └── ...
 *
 * Flow:
 *   1. POST /textbook { topic, language, llm }               → { questions, checklist }
 *      Run ONCE, by the first target LLM, and saved to context.json. If
 *      context.json already exists in the prompt directory it is REUSED and
 *      call 1 is skipped, so every model generates from the SAME context.
 *   2. Auto-answer: each question → its own `default`; checklist → the checked
 *      items (or ALL items with --checklist=all, or all items when nothing is
 *      checked). Stored in context.json as { answers, checklist }.
 *   3. For EACH target LLM: POST /textbook { ..., context }  → { title, groups }
 *      and write <language>-<model>.yaml.
 *
 * File shape (per model):
 *   - Above the divider: `ideal` — hand-editable YAML, English-only fields
 *     (phrasebook `title`, group `title`, each card's English gloss). Seeded
 *     once from the first real response, then preserved across reruns (pass
 *     --force to reseed). Add a free-form `note:`/`notes:` to explain a gap.
 *   - Below the divider: `actual` — the verbatim request inputs + the raw
 *     questions response + the raw generate response + a timestamp, byte-for-
 *     byte what the API returned. Fully replaced on every run; never hand-edit.
 *
 * USAGE
 *   # New prompt: seed context.json (via the first LLM) and run every model.
 *   deno run --allow-net --allow-read --allow-write evals/eval-textbook.js \
 *     --topic="salsa dancing in austin, tx" --language=es \
 *     [--llm=all] [--checklist=default|all] [--url=http://localhost:8080] [--force]
 *
 *   # Rerun: from inside a prompt directory (it has context.json), the saved
 *   # prompt is reused and the model files are overwritten. --dir=PATH does the
 *   # same without cd-ing.
 *   cd evals/salsa-dancing-in-austin-tx && deno run ../eval-textbook.js
 *
 * --llm accepts `all` (default — every model), a single model, or a
 * comma-separated subset (e.g. --llm=google,claude). topic/language are read
 * from context.json when present; otherwise they come from flags or an
 * interactive prompt (requires a real TTY on stdin).
 *
 * Requires the dev server already running (`cd src && npm run dev`).
 */

const ENUMS = {
  language: ['zh', 'ja', 'es', 'cs'],
  llm: ['google', 'g-flash', 'claude', 'chatgpt'],
  checklist: ['default', 'all'],
};
const ALL_LLMS = ENUMS.llm;
const DEFAULTS = { llm: 'all', checklist: 'default' };

const EVALS_DIR = new URL('./', import.meta.url);
const CONTEXT_FILE = 'context.json';
const DIVIDER = [
  '# ============================================================',
  '# ACTUAL — regenerated by eval-textbook.js on every run.',
  '# Everything below this line is discarded and replaced on rerun.',
  '# ============================================================',
].join('\n');

// ---------------------------------------------------------------------------
// CLI args + interactive prompting
// ---------------------------------------------------------------------------

function parseFlags(argv) {
  const flags = { url: 'http://localhost:8080', force: false };
  for (const arg of argv) {
    if (arg === '--force') flags.force = true;
    else if (arg.startsWith('--')) {
      const eq = arg.indexOf('=');
      if (eq === -1) throw new Error(`Malformed flag (expected --key=value): ${arg}`);
      flags[arg.slice(2, eq)] = arg.slice(eq + 1);
    } else {
      throw new Error(`Unexpected argument: ${arg}`);
    }
  }
  return flags;
}

function promptTopic(flags) {
  if (flags.topic) return flags.topic;
  const answer = prompt('Topic (the situation, e.g. "salsa dancing" or "dinner with my in-laws"): ');
  if (answer === null) {
    throw new Error(
      'No value for "topic" and stdin is not an interactive terminal. ' +
      'Pass --topic (or run inside a prompt directory that has context.json).',
    );
  }
  const trimmed = answer.trim();
  if (!trimmed) throw new Error('Topic is required.');
  return trimmed;
}

function promptEnum(flags, key, { required }) {
  if (flags[key]) {
    if (!ENUMS[key].includes(flags[key])) {
      throw new Error(`--${key}=${flags[key]} invalid; must be one of ${ENUMS[key].join(', ')}`);
    }
    return flags[key];
  }
  const def = DEFAULTS[key];
  const suffix = required ? '' : ` (default: ${def})`;
  const label = `${key[0].toUpperCase()}${key.slice(1)} [${ENUMS[key].join('|')}]${suffix}: `;
  for (;;) {
    const raw = prompt(label);
    if (raw === null) {
      // stdin is not an interactive terminal.
      if (!required) return def;
      throw new Error(
        `No value for "${label}" and stdin is not an interactive terminal. ` +
        'Pass every param as a --flag for non-interactive use.',
      );
    }
    const answer = raw.trim();
    if (!answer && !required) return def;
    if (ENUMS[key].includes(answer)) return answer;
    console.log(`  invalid — must be one of ${ENUMS[key].join(', ')}`);
  }
}

// --llm=all → every model; a single model or comma list → that subset.
function resolveLlms(value) {
  const raw = value || DEFAULTS.llm;
  if (raw === 'all') return [...ALL_LLMS];
  const llms = raw.split(',').map((s) => s.trim()).filter(Boolean);
  const bad = llms.filter((l) => !ALL_LLMS.includes(l));
  if (bad.length) {
    throw new Error(`--llm=${raw} invalid; use "all", or one/comma-list of ${ALL_LLMS.join(', ')}`);
  }
  return llms;
}

// Sample filenames encode the served model by nickname (gpt-5.6-luna → "luna").
// Falls back to the raw served model string, then the llm enum.
const MODEL_NICKNAMES = {
  'gemini-3.5-flash-lite': 'gemini',
  'gemini-3.8-flash': 'g-flash',
  'gpt-5.6-luna': 'luna',
  'claude-haiku-4-5-20251001': 'haiku',
};

function slug(str) {
  return String(str)
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function toDirUrl(path, base = Deno.cwd()) {
  const withSlash = path.endsWith('/') ? path : `${path}/`;
  const baseSlash = base.endsWith('/') ? base : `${base}/`;
  return new URL(withSlash, `file://${baseSlash}`);
}

// ---------------------------------------------------------------------------
// minimal YAML emitter — just enough for the `ideal` shape (nested
// lists/dicts of strings). Not a general-purpose serializer.
// ---------------------------------------------------------------------------

function yamlScalar(value) {
  if (value === null || value === undefined) return 'null';
  const s = String(value);
  return `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

function emitIdealYaml(ideal, context) {
  const lines = [];
  lines.push('# ideal — hand-edit this section; preserved across reruns.');
  lines.push('# English-only. Edit gloss/title text, add or remove cards, reorder groups.');
  lines.push('# Add a `note:` field to any group (or a top-level `notes:`) to explain a');
  lines.push('# gap between ideal and actual (e.g. "too few standalone vocab words here").');
  lines.push(`title: ${yamlScalar(ideal.title)}`);

  // context — the call-1 answers + section checklist that drove generation.
  // Seeded from the actual run so the questions themselves can be reviewed:
  // fix a wrong answer, drop an irrelevant section, or add an inline `#`
  // comment beside any line to critique a question or section choice.
  const answerKeys = Object.keys(context.answers);
  if (answerKeys.length === 0) {
    lines.push('answers: {}');
  } else {
    lines.push('answers:');
    for (const key of answerKeys) {
      lines.push(`  ${yamlScalar(key)}: ${yamlScalar(context.answers[key])}`);
    }
  }
  if (context.checklist.length === 0) {
    lines.push('checklist: []');
  } else {
    lines.push('checklist:');
    for (const item of context.checklist) lines.push(`  - ${yamlScalar(item)}`);
  }

  if (ideal.groups.length === 0) {
    lines.push('groups: []');
  } else {
    lines.push('groups:');
    for (const group of ideal.groups) {
      lines.push(`  - title: ${yamlScalar(group.title)}`);
      if (group.cards.length === 0) {
        lines.push('    cards: []');
      } else {
        lines.push('    cards:');
        for (const card of group.cards) lines.push(`      - ${yamlScalar(card)}`);
      }
    }
  }
  lines.push('notes: ""');
  return lines.join('\n');
}

// ---------------------------------------------------------------------------
// strip a raw /textbook generate response to English-only fields for the seed
// ---------------------------------------------------------------------------

function stripToEnglish(response) {
  return {
    title: response.title || null,
    groups: (response.groups || []).map((group) => ({
      title: group.title,
      cards: (group.cards || []).map((c) => c.translation),
    })),
  };
}

// ---------------------------------------------------------------------------
// build the generate-call `context` from the questions response
// ---------------------------------------------------------------------------

function buildContext(questionsResponse, mode) {
  const answers = {};
  for (const q of questionsResponse.questions || []) {
    answers[q.label] = q.default;
  }
  const all = (questionsResponse.checklist || []).map((c) => c.label);
  const checked = (questionsResponse.checklist || [])
    .filter((c) => c.checked)
    .map((c) => c.label);
  // 'all' takes every item; 'default' takes the checked ones, but falls back
  // to all when the model checked nothing (so a sample is never empty).
  const checklist = mode === 'all' || checked.length === 0 ? all : checked;
  return { answers, checklist };
}

// ---------------------------------------------------------------------------
// runner
// ---------------------------------------------------------------------------

async function postTextbook(url, body) {
  const res = await fetch(`${url}/textbook`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(body),
  });
  const payload = await res.json();
  if (!res.ok) {
    throw new Error(`/textbook returned ${res.status}: ${payload.error || JSON.stringify(payload)}`);
  }
  return payload;
}

// Resolve the prompt directory + whether an existing context.json is reused.
// Priority: --dir → --topic (→ evals/<slug>/) → invocation cwd (rerun in place).
function resolveWorkDir(flags) {
  if (flags.dir) return toDirUrl(flags.dir);
  if (flags.topic) return new URL(`${slug(flags.topic)}/`, EVALS_DIR);
  return toDirUrl(invocationCwd());
}

// npm invokes the script from src/ but sets INIT_CWD to where the user ran it,
// so a bare `npm run eval:textbook` from inside a prompt dir still resolves it.
// Falls back to Deno.cwd() when --allow-env was not granted.
function invocationCwd() {
  try {
    const init = Deno.env.get('INIT_CWD');
    if (init) return init;
  } catch (_) { /* no env permission — cwd is enough for `deno run` in-dir */ }
  return Deno.cwd();
}

async function readContext(dirUrl) {
  try {
    return JSON.parse(await Deno.readTextFile(new URL(CONTEXT_FILE, dirUrl)));
  } catch (err) {
    if (err instanceof Deno.errors.NotFound) return null;
    throw err;
  }
}

// Write (or refresh) one model's <language>-<model>.yaml, preserving the
// hand-edited ideal section unless --force reseeds it.
async function writeSample(dirUrl, { input, context, questionsResponse, generateResponse, force }) {
  const servedModel = generateResponse && generateResponse.usage && generateResponse.usage.model;
  const model = MODEL_NICKNAMES[servedModel] || servedModel || input.llm;
  const fileUrl = new URL(`${slug(`${input.language}-${model}`)}.yaml`, dirUrl);

  const questionsAndAnswers = (questionsResponse.questions || []).map((q) => ({
    question: q.label,
    options: q.options,
    answer: context.answers[q.label],
  }));

  const actualBlock = JSON.stringify(
    {
      input,
      context,
      generatedAt: new Date().toISOString(),
      questionsAndAnswers,
      questionsResponse,
      generateResponse,
    },
    null,
    2,
  );

  let idealSection;
  let priorContent = null;
  try {
    priorContent = await Deno.readTextFile(fileUrl);
  } catch (err) {
    if (!(err instanceof Deno.errors.NotFound)) throw err;
  }

  if (priorContent !== null && !force) {
    const dividerIdx = priorContent.indexOf(DIVIDER);
    idealSection = dividerIdx === -1 ? priorContent.trimEnd() : priorContent.slice(0, dividerIdx).trimEnd();
  } else {
    idealSection = emitIdealYaml(stripToEnglish(generateResponse), context);
  }

  const content = `${idealSection}\n\n${DIVIDER}\n${actualBlock}\n`;
  await Deno.writeTextFile(fileUrl, content);
  return { fileUrl, model, seeded: priorContent === null || force };
}

async function main() {
  const flags = parseFlags(Deno.args);
  const llms = resolveLlms(flags.llm);

  let workDir = resolveWorkDir(flags);
  let saved = await readContext(workDir);

  let topic;
  let language;
  let questionsResponse;
  let context;

  if (saved) {
    if (!saved.topic || !saved.language || !saved.context) {
      throw new Error(`${new URL(CONTEXT_FILE, workDir).pathname} is malformed (missing topic/language/context)`);
    }
    topic = saved.topic;
    language = saved.language;
    questionsResponse = saved.questionsResponse || { questions: [], checklist: [] };
    context = saved.context;
    if (flags.language && flags.language !== language) {
      console.warn(`  ⚠ --language=${flags.language} ignored; context.json is "${language}"`);
    }
    console.log(`Reusing prompt from ${workDir.pathname}context.json: "${topic}" (${language}) — ${context.checklist.length} section(s)`);
  } else {
    // No pinned context — this is a new prompt. Collect topic/language, then
    // let the FIRST target LLM run call 1 and seed context.json.
    topic = promptTopic(flags);
    language = promptEnum(flags, 'language', { required: true });
    const checklistMode = promptEnum(flags, 'checklist', { required: false });

    // Anchor a new prompt at evals/<slug>/ unless the caller pinned --dir.
    if (!flags.dir) workDir = new URL(`${slug(topic)}/`, EVALS_DIR);

    const firstLlm = llms[0];
    console.log(`Call 1 — ${flags.url}/textbook (questions) for "${topic}" (${language}, ${firstLlm})...`);
    questionsResponse = await postTextbook(flags.url, { topic, language, llm: firstLlm });
    console.log(`  ${questionsResponse.questions.length} questions, ${questionsResponse.checklist.length} checklist items`);
    context = buildContext(questionsResponse, checklistMode);

    await Deno.mkdir(workDir, { recursive: true });
    await Deno.writeTextFile(
      new URL(CONTEXT_FILE, workDir),
      `${JSON.stringify({ topic, language, questionsResponse, context }, null, 2)}\n`,
    );
    console.log(`Wrote ${new URL(CONTEXT_FILE, workDir).pathname} — shared by every model`);
  }

  await Deno.mkdir(workDir, { recursive: true });
  console.log(`Generating ${llms.length} model(s): ${llms.join(', ')} — ${context.checklist.length} section(s)\n`);

  const failures = [];
  for (const llm of llms) {
    const input = { topic, language, llm };
    try {
      const generateResponse = await postTextbook(flags.url, { topic, language, llm, context });
      const cardCount = (generateResponse.groups || []).reduce((n, g) => n + g.cards.length, 0);
      const { fileUrl, seeded } = await writeSample(workDir, {
        input,
        context,
        questionsResponse,
        generateResponse,
        force: flags.force,
      });
      console.log(`✓ ${llm}: ${generateResponse.groups.length} groups, ${cardCount} cards → ${fileUrl.pathname}${seeded ? ' (seeded ideal)' : ' (preserved ideal)'}`);
    } catch (err) {
      failures.push({ llm, message: err.message });
      console.log(`✗ ${llm}: ${err.message}`);
    }
  }

  console.log(`\nDone: ${llms.length - failures.length}/${llms.length} model(s) succeeded.`);
  if (failures.length) Deno.exit(1);
}

if (import.meta.main) {
  main().catch((err) => {
    console.error('eval-textbook failed:', err.message);
    Deno.exit(1);
  });
}

export { slug, stripToEnglish, emitIdealYaml, buildContext, resolveLlms, DIVIDER };
