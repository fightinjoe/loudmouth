#!/usr/bin/env -S deno run --allow-net --allow-read --allow-write

/**
 * Subjective-review sample generator for /lookup (companion to lookup.eval.js,
 * which checks OBJECTIVE structural/reading/judge correctness). This script
 * is for the human-in-the-loop loop of "look at real output, decide what a
 * better output would be, mine the differences for prompt edits" — see
 * api/.claude/skills/prompt-review.
 *
 * It queries the REAL, already-running dev server (no prompt fork, no mocked
 * LLM) and writes one file per case to api/evals/samples/<slug>.yaml:
 *
 *   - Above the divider: `ideal` — hand-editable YAML, English-only fields
 *     (block `definition`, card English gloss, group `title`). Seeded once
 *     from the first real response, then NEVER touched again by this script.
 *     Add a free-form `notes:` anywhere to explain a gap between ideal and
 *     actual (e.g. "actual" merged two situations that should be separate
 *     groups).
 *   - Below the divider: `actual` — the verbatim request input + timestamp +
 *     raw /lookup JSON response, byte-identical to what the API returned.
 *     Fully replaced on every run; never hand-edit this section, it will be
 *     discarded.
 *
 * This file is for a human/LLM to read side by side, not for a script to
 * parse back — it is intentionally not one valid YAML or JSON document.
 *
 * USAGE
 *   deno run --allow-net --allow-read --allow-write evals/lookup-sample.js \
 *     [--term=bathroom] [--language=ja] [--ability=beginner] [--formality=casual] \
 *     [--audience=staff] [--llm=google] [--url=http://localhost:8080] [--force]
 *
 * Any of term/language/ability/formality/audience/llm omitted as a flag is
 * prompted for interactively (requires a real TTY on stdin — pass every flag
 * for non-interactive/scripted use, e.g. from the prompt-review skill).
 *
 * Requires the dev server already running (`cd src && npm run dev`).
 */

const ENUMS = {
  language: ['zh', 'ja', 'es', 'cs'],
  ability: ['none', 'beginner', 'intermediate', 'advanced'],
  formality: ['casual', 'polite', 'formal'],
  audience: ['stranger', 'staff', 'acquaintance', 'family'],
  llm: ['google', 'claude', 'chatgpt'],
};
const DEFAULTS = { ability: 'beginner', formality: 'polite', audience: 'staff', llm: 'google' };

const SAMPLES_DIR = new URL('./samples/', import.meta.url);
const DIVIDER = [
  '# ============================================================',
  '# ACTUAL — regenerated by lookup-sample.js on every run.',
  '# Everything below this line is discarded and replaced on rerun.',
  '# ============================================================',
].join('\n');

// ---------------------------------------------------------------------------
// CLI args + interactive prompting
// ---------------------------------------------------------------------------

function parseFlags(argv) {
  const flags = { url: 'http://localhost:8080', force: false };
  for (const arg of argv) {
    if (arg === '--force') flags.force = true;
    else if (arg.startsWith('--')) {
      const eq = arg.indexOf('=');
      if (eq === -1) throw new Error(`Malformed flag (expected --key=value): ${arg}`);
      flags[arg.slice(2, eq)] = arg.slice(eq + 1);
    }
  }
  return flags;
}

function askLine(label) {
  const answer = prompt(label);
  if (answer === null) {
    throw new Error(
      `No value for "${label}" and stdin is not an interactive terminal. ` +
      'Pass every param as a --flag for non-interactive use.',
    );
  }
  return answer.trim();
}

function promptTerm(flags) {
  if (flags.term) return flags.term;
  const term = askLine('Term (English word or phrase, e.g. "bathroom" or "surf (v. to ride a wave)"): ');
  if (!term) throw new Error('Term is required.');
  return term;
}

function promptEnum(flags, key, { required }) {
  if (flags[key]) {
    if (!ENUMS[key].includes(flags[key])) {
      throw new Error(`--${key}=${flags[key]} invalid; must be one of ${ENUMS[key].join(', ')}`);
    }
    return flags[key];
  }
  const def = DEFAULTS[key];
  const suffix = required ? '' : ` (default: ${def})`;
  const label = `${key[0].toUpperCase()}${key.slice(1)} [${ENUMS[key].join('|')}]${suffix}: `;
  for (;;) {
    const raw = prompt(label);
    if (raw === null) {
      // stdin is not an interactive terminal.
      if (!required) return def;
      throw new Error(
        `No value for "${label}" and stdin is not an interactive terminal. ` +
        'Pass every param as a --flag for non-interactive use.',
      );
    }
    const answer = raw.trim();
    if (!answer && !required) return def;
    if (ENUMS[key].includes(answer)) return answer;
    console.log(`  invalid — must be one of ${ENUMS[key].join(', ')}`);
  }
}

function collectInput(flags) {
  return {
    term: promptTerm(flags),
    language: promptEnum(flags, 'language', { required: true }),
    ability: promptEnum(flags, 'ability', { required: false }),
    formality: promptEnum(flags, 'formality', { required: false }),
    audience: promptEnum(flags, 'audience', { required: false }),
    llm: promptEnum(flags, 'llm', { required: false }),
  };
}

function slugify({ term, language, ability, formality, audience, llm }) {
  const raw = `${term}-${language}-${ability}-${formality}-${audience}-${llm}`;
  return raw
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

// ---------------------------------------------------------------------------
// minimal YAML emitter — just enough for the `ideal` shape (nested
// lists/dicts of strings). Not a general-purpose serializer.
// ---------------------------------------------------------------------------

function yamlScalar(value) {
  if (value === null || value === undefined) return 'null';
  const s = String(value);
  return `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

function emitIdealYaml(ideal) {
  const lines = [];
  lines.push('# ideal — hand-edit this section; preserved across reruns.');
  lines.push('# Add a `notes:` field anywhere to explain a gap between ideal and actual.');
  lines.push('blocks:');
  for (const block of ideal.blocks) {
    lines.push(`  - definition: ${yamlScalar(block.definition)}`);
    lines.push(`    card: ${yamlScalar(block.card)}`);
    if (block.groups.length === 0) {
      lines.push('    groups: []');
    } else {
      lines.push('    groups:');
      for (const group of block.groups) {
        lines.push(`      - title: ${yamlScalar(group.title)}`);
        if (group.cards.length === 0) {
          lines.push('        cards: []');
        } else {
          lines.push('        cards:');
          for (const card of group.cards) lines.push(`          - ${yamlScalar(card)}`);
        }
      }
    }
  }
  lines.push('notes: ""');
  return lines.join('\n');
}

// ---------------------------------------------------------------------------
// strip a raw /lookup response to English-only fields for the `ideal` seed
// ---------------------------------------------------------------------------

function stripToEnglish(response) {
  return {
    blocks: (response.blocks || []).map((block) => ({
      definition: block.card && block.card.definition ? block.card.definition : null,
      card: block.card ? block.card.translation : null,
      groups: (block.groups || []).map((group) => ({
        title: group.title,
        cards: (group.cards || []).map((c) => c.translation),
      })),
    })),
  };
}

// ---------------------------------------------------------------------------
// runner
// ---------------------------------------------------------------------------

async function fetchLookup(url, input) {
  const res = await fetch(`${url}/lookup`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(input),
  });
  const body = await res.json();
  if (!res.ok) {
    throw new Error(`/lookup returned ${res.status}: ${body.error || JSON.stringify(body)}`);
  }
  return body;
}

async function main() {
  const flags = parseFlags(Deno.args);
  const input = collectInput(flags);

  console.log(`Querying ${flags.url}/lookup for "${input.term}" (${input.language}, ${input.ability}/${input.formality}/${input.audience}, ${input.llm})...`);
  const response = await fetchLookup(flags.url, input);

  await Deno.mkdir(SAMPLES_DIR, { recursive: true });
  const fileUrl = new URL(`./${slugify(input)}.yaml`, SAMPLES_DIR);

  const actualBlock = JSON.stringify(
    { input, generatedAt: new Date().toISOString(), response },
    null,
    2,
  );

  let idealSection;
  let exists = true;
  let priorContent = null;
  try {
    priorContent = await Deno.readTextFile(fileUrl);
  } catch (err) {
    if (err instanceof Deno.errors.NotFound) exists = false;
    else throw err;
  }

  if (exists && !flags.force) {
    const dividerIdx = priorContent.indexOf(DIVIDER);
    idealSection = dividerIdx === -1 ? priorContent.trimEnd() : priorContent.slice(0, dividerIdx).trimEnd();
    console.log(`Preserving existing ideal section in ${fileUrl.pathname}`);
  } else {
    idealSection = emitIdealYaml(stripToEnglish(response));
    console.log(exists ? 'Force-regenerating ideal + actual.' : 'Seeding new ideal section from this response.');
  }

  const content = `${idealSection}\n\n${DIVIDER}\n${actualBlock}\n`;
  await Deno.writeTextFile(fileUrl, content);
  console.log(`Wrote ${fileUrl.pathname}`);
}

if (import.meta.main) {
  main().catch((err) => {
    console.error('lookup-sample failed:', err.message);
    Deno.exit(1);
  });
}

export { slugify, stripToEnglish, emitIdealYaml, DIVIDER };
